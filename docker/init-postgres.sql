-- Create user for Odoo
CREATE USER odoo WITH PASSWORD 'odoo';
GRANT USAGE ON SCHEMA public TO odoo;

ALTER USER odoo CREATEDB;
ALTER DEFAULT PRIVILEGES FOR USER odoo IN SCHEMA public GRANT ALL ON TABLES TO odoo;
ALTER DEFAULT PRIVILEGES FOR USER odoo IN SCHEMA public GRANT ALL ON SEQUENCES TO odoo;
ALTER DEFAULT PRIVILEGES FOR USER odoo IN SCHEMA public GRANT ALL ON FUNCTIONS TO odoo;